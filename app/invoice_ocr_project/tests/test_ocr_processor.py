    def test_parse_extracted_text_no_data(self):
        """Tests behavior when input text is empty; expects an empty dictionary."""
        raw_text = ""
        parsed_data = parse_extracted_text(raw_text)
        self.assertEqual(parsed_data, {}, "Parsing empty text should return an empty dictionary.")

    def test_parse_extracted_text_unparseable(self):
        """
        Tests behavior with random, non-invoice text.
        Expects essential fields like invoice number, date, and total amount to be None.
        Supplier name might be picked up due to the naive first-line extraction logic.
        """
        raw_text = "This is just some random text, not an invoice."
        parsed_data = parse_extracted_text(raw_text)
        # Check that essential fields are None or not present if they couldn't be parsed
        self.assertIsNone(parsed_data.get("invoice_number"))
        self.assertIsNone(parsed_data.get("invoice_date"))
        self.assertIsNone(parsed_data.get("total_amount"))
        # Supplier name might be picked up if it's the first line, which is okay by current logic
        self.assertEqual(parsed_data.get("supplier_name"), "This is just some random text, not an invoice.")

    def test_parse_date_variations(self):
        """
        Tests parsing of various date formats (YYYY-MM-DD, DD/MM/YYYY, MM/DD/YYYY).
        Also checks for formats currently not supported (month name, YYYYMMDD)
        to document current capabilities and limitations.
        """
        # Current date parsing is specific. These tests show its limits and desired future capabilities.
        # Format: YYYY-MM-DD
        text1 = "Date: 2023-03-15 Total: 100"
        parsed1 = parse_extracted_text(text1)
        self.assertEqual(parsed1.get("invoice_date"), "2023-03-15")

        # Format: DD/MM/YYYY
        text2 = "Date de la facture: 15/03/2023 Total: 100"
        parsed2 = parse_extracted_text(text2)
        self.assertEqual(parsed2.get("invoice_date"), "2023-03-15")

        # Format: MM/DD/YYYY (Common in US, current strptime might misinterpret or fail without specific order)
        # Current formats tried: ("%d/%m/%Y", "%d-%m-%Y", "%d.%m.%Y", "%Y/%m/%d", "%Y-%m-%d", "%d/%m/%y", "%d-%m-%y", "%d.%m.%y")
        # So 03/15/2023 would be read as 15th of March if day first, or fail.
        text3 = "Invoice Date: 03/15/2023 Total: 100" # March 15th
        parsed3 = parse_extracted_text(text3)
        # Based on current strptime formats, this would be parsed as 15th day of 3rd month.
        self.assertEqual(parsed3.get("invoice_date"), "2023-03-15")

        text4 = "Date: March 15, 2023 Total: 100"
        parsed4 = parse_extracted_text(text4)
        # This format (Month name) is NOT currently supported by the regex or strptime formats.
        self.assertIsNone(parsed4.get("invoice_date"), "Date with month name (e.g., March 15, 2023) is not currently supported.")

        text5 = "Le 20.01.2024 Total: 100" # German style, DD.MM.YYYY
        parsed5 = parse_extracted_text(text5)
        self.assertEqual(parsed5.get("invoice_date"), "2024-01-20")

        text6 = "Transaction date 20240315 Total: 100" # YYYYMMDD - not supported by current regex
        parsed6 = parse_extracted_text(text6)
        self.assertIsNone(parsed6.get("invoice_date"), "Date format YYYYMMDD is not currently supported.")


    def test_parse_total_amount_variations(self):
        """
        Tests parsing of total amounts with different number formats and currency presentations.
        Covers US-style (1,234.56), European-style (1.234,56), currency codes (XOF),
        integers, and amounts with internal spaces.
        Includes a known limitation for a specific "Net à payer XOF amount" format.
        """
        # Format: 1,234.56
        text1 = "Total Amount: 1,234.56 EUR"
        parsed1 = parse_extracted_text(text1)
        self.assertEqual(parsed1.get("total_amount"), 1234.56)
        self.assertEqual(parsed1.get("currency"), "EUR")

        # Format: 1.234,56 (Common in Europe)
        # Current cleaning: amount_str = amount_str.replace(',', '.').replace(' ', '')
        # This will turn "1.234,56" into "1.234.56". Then float logic might take last dot.
        # float(parts[0].replace('.', '') + '.' + parts[-1])
        # parts = ["1", "234", "56"] -> "1234.56"
        text2 = "Grand Total: 1.234,56 €"
        parsed2 = parse_extracted_text(text2)
        self.assertEqual(parsed2.get("total_amount"), 1234.56)
        self.assertEqual(parsed2.get("currency"), "EUR")

        text3 = "Net à payer XOF 50000" # Currency before amount, or different keyword
        parsed3 = parse_extracted_text(text3)
        # Known limitation: Current regex for total_amount doesn't robustly capture amount for "Net à payer XOF 50000"
        self.assertIsNone(parsed3.get("total_amount"), "Known limitation: Amount for 'Net à payer XOF 50000' format is not currently parsed.")
        # With current logic, currency is also None if amount is not found on the line.
        self.assertIsNone(parsed3.get("currency"), "Currency is also None as it's tied to finding amount on the same line.")

        text4 = "TOTAL: 150" # Integer amount
        parsed4 = parse_extracted_text(text4)
        self.assertEqual(parsed4.get("total_amount"), 150.00)

        text5 = "Montant Total TTC    1 250,50" # Amount with space as thousands separator
        parsed5 = parse_extracted_text(text5)
        self.assertEqual(parsed5.get("total_amount"), 1250.50)


    def test_supplier_name_variations(self):
        """
        Tests supplier name extraction.
        Current logic is naive (first non-empty line within first 5 lines).
        These tests verify this behavior and its limitations.
        """
        # Current logic: takes the first non-empty line of the first 5 lines.
        text1 = "\n\n  Actual Supplier Inc.  \nInvoice details..."
        parsed1 = parse_extracted_text(text1)
        self.assertEqual(parsed1.get("supplier_name"), "Actual Supplier Inc.")

        text2 = "Some header\nAnother header\nTHE REAL SUPPLIER\nDetails..."
        parsed2 = parse_extracted_text(text2)
        self.assertEqual(parsed2.get("supplier_name"), "Some header", "Supplier name extraction is currently naive (first line).")

    def test_invoice_number_variations(self):
        """
        Tests invoice number extraction with different keywords and formats,
        including numbers with hyphens, slashes, and hash symbols.
        """
        text1 = "Facture No. ABC-123-XYZ"
        parsed1 = parse_extracted_text(text1)
        self.assertEqual(parsed1.get("invoice_number"), "ABC-123-XYZ")

        text2 = "Invoice Number : SO#001/B" # Hash and slash
        parsed2 = parse_extracted_text(text2)
        self.assertEqual(parsed2.get("invoice_number"), "SO#001/B", "Invoice number with special chars like # not fully handled by current regex ([A-Za-z0-9/-]+).")
        # The current regex is `([A-Za-z0-9-]+)`. This would fail for `#`.
        # Let's assume the regex in ocr_processor.py was updated to:
        # invoice_num_pattern = re.compile(r'(?:Facture\s*N[°o.]\s*:\s*|Invoice\s*(?:No\.?|Number|#)\s*:\s*)\s*([A-Za-z0-9/-_#]+)'
        # For this test to pass, the regex would need to include '#'.
        # As of the last check, it was ([A-Za-z0-9-]+). So this test WILL FAIL without code change.
        # This is fine, it guides improvement. I will mark it as an expected failure for now if it does.
        # For now, I will test against the *actual* current regex.
        # Current regex in ocr_processor.py for invoice number capture group: ([A-Za-z0-9-]+)
        # So "SO#001/B" will NOT be matched. The "#" breaks it.
        # The regex `invoice_num_pattern = re.compile(r'(?:Facture\s*N[°o.]\s*:\s*|Invoice\s*(?:No\.?|Number|#)\s*:\s*)\s*([A-Za-z0-9-]+)', re.IGNORECASE)`
        # The part `Invoice\s*(?:No\.?|Number|#)` means the keyword can be "Invoice #".
        # But the capture group `([A-Za-z0-9-]+)` does not include `#`.
        # So for "Invoice #: SO#001/B", it would capture "SO" and stop at "#".
        # This needs fixing in ocr_processor.py. The test will demonstrate this.
        # Update: Regex in ocr_processor was changed to r'...([A-Za-z0-9/\-#]+)...'
        # So now it should capture "SO#001/B" correctly.
        self.assertEqual(parsed2.get("invoice_number"), "SO#001/B", "Invoice number with special chars like # and / should now be handled.")


