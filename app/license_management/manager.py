def activate_license(conn, user_id: str, license_key: str) -> tuple[bool, str]:
    """
    Activates a new license for the user using the provided key.
    Deactivates any existing active license for the user.
    """
    logger.info(f"Attempting to activate license key '{license_key}' for user_id '{user_id}'.")

    is_valid_format, key_error_msg, key_payload = verify_license_key_signature(license_key)
    if not is_valid_format:
        logger.warning(f"License key '{license_key}' failed signature/format verification: {key_error_msg}")
        return False, key_error_msg or "Clé de licence invalide ou corrompue."

    # Placeholder: In a real system, key_payload would contain more info like duration, type.
    # For now, assume the key is for a 'complet' license and has a standard duration (e.g., 1 year).
    # This part needs to be more robust if keys carry specific data.
    # For this implementation, we'll assume the key primarily serves as an activation token,
    # and the license type/duration are somewhat fixed or determined by other means for this example.

    # Check if this specific key has already been activated on *this* machine by *this* user
    # (or globally if keys are single-use across all machines/users)
    # For simplicity, let's check if this key is *already active* for this user.
    # A more robust check would be if the key is tied to a specific machine ID in its payload,
    # or if the key is globally unique and has been used anywhere.

    existing_key_usage = licenses_crud.get_license_by_key(conn, license_key)
    current_machine_id = get_machine_identifier()

    if existing_key_usage:
        if existing_key_usage['is_active'] and existing_key_usage['machine_info'] == current_machine_id and existing_key_usage['user_id'] == user_id:
            return True, "Cette clé de licence est déjà active pour vous sur cette machine."
        elif existing_key_usage['machine_info'] != current_machine_id:
             # This logic might be too strict if licenses are meant to be transferrable under certain conditions
            logger.warning(f"License key '{license_key}' already used on a different machine: {existing_key_usage['machine_info']}.")
            return False, "Cette clé de licence a déjà été utilisée sur une autre machine."
        # If used by another user, or inactive but on this machine, allow re-activation for *this* user (overwrites)

    # Deactivate any existing active license for this user
    active_license = licenses_crud.get_active_license_for_user(conn, user_id)
    if active_license:
        licenses_crud.deactivate_license(conn, active_license['license_id'])
        logger.info(f"Deactivated existing license '{active_license['license_id']}' for user '{user_id}'.")
        if activity_logs_crud:
            activity_logs_crud.add_activity_log(conn=conn, data={
                "user_id": user_id, "action_type": "LICENSE_DEACTIVATED_FOR_NEW",
                "details": f"Existing license {active_license['license_id']} (type: {active_license['license_type']}) deactivated due to new license activation.",
                "related_entity_type": "License", "related_entity_id": active_license['license_id']
            })


    # Determine license type and duration from key_payload (if available) or use defaults
    # This is simplified; real keys would securely embed this.
    license_type_from_key = key_payload.get("license_type", "complet")
    # Duration could also come from key_payload. Defaulting to 1 year for purchased keys.
    duration_days = key_payload.get("duration_days", 365)

    now = datetime.now(timezone.utc)
    expiration = now + timedelta(days=duration_days)

    new_license_data = create_license_record(
        user_id=user_id,
        license_type=license_type_from_key, # e.g., 'complet'
        license_key=license_key,
        activation_date=now,
        expiration_date=expiration,
        machine_info=current_machine_id,
        is_active=True
    )

    new_license_id = licenses_crud.add_license(conn, new_license_data)
    if new_license_id:
        logger.info(f"License key '{license_key}' activated successfully for user '{user_id}'. New license ID: {new_license_id}, Type: {license_type_from_key}, Expires: {expiration.isoformat()}")
        if activity_logs_crud:
             activity_logs_crud.add_activity_log(conn=conn, data={
                "user_id": user_id, "action_type": "LICENSE_ACTIVATED_KEY",
                "details": f"License activated with key {license_key}. Type: {license_type_from_key}, Expires: {expiration.isoformat()}.",
                "related_entity_type": "License", "related_entity_id": new_license_id
            })
        return True, f"Licence '{license_type_from_key.capitalize()}' activée avec succès. Valide jusqu'au {expiration.strftime('%d/%m/%Y %H:%M')}."
    else:
        logger.error(f"Failed to add new license record to DB for user '{user_id}' with key '{license_key}'.")
        return False, "Erreur lors de l'enregistrement de la nouvelle licence dans la base de données."


