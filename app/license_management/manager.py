def get_machine_identifier() -> str:
    """Generates a unique identifier for the current machine."""
    logger = logging.getLogger(__name__)
    try:
        # Concatenate various machine-specific details
        # Using a fixed string if some info is unavailable to ensure it still runs
        system_info = f"{platform.system()}-{platform.node()}-{platform.machine()}-{platform.processor()}"
        # Add a UUID based on hardware address (MAC address) if available
        # getnode() returns a 48-bit integer
        mac_address = str(uuid.getnode())
        combined_info = f"{system_info}-{mac_address}"

        # Hash the combined information to create a fixed-length identifier
        hashed_info = hashlib.sha256(combined_info.encode('utf-8')).hexdigest()
        return hashed_info
    except Exception as e:
        logger.error(f"Error generating machine identifier: {e}", exc_info=True)
        # Fallback to a more generic but still somewhat unique ID
        return hashlib.sha256(f"{platform.system()}-{platform.node()}-{str(uuid.uuid4())}".encode('utf-8')).hexdigest()

