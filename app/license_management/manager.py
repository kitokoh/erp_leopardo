def create_default_admin_license(conn, user_id: str) -> tuple[bool, str, dict | None]:
    """
    Creates a default 6-month 'complet' license for the specified user (typically admin).
    This is usually called if the admin logs in and has no valid license,
    AND no other 'complet' license exists in the system for any user.
    """
    logger.info(f"Attempting to create default admin license for user_id '{user_id}'.")

    # Check if any other 'complet' license is active in the system.
    # This is a policy decision: do we allow multiple 'complet' licenses if admin's expires?
    # For now, let's assume the original intent: create if admin's is bad AND *no other 'complet' exists*.
    # This might be too restrictive. A common scenario: admin sets up, other users get 'complet' licenses.
    # If admin's own license lapses, they should still be able to get a new default one to manage the system.
    # So, the check `has_any_active_complete_license` might be more about initial system setup.
    # Let's adjust: The admin should always be able to get a license if theirs is invalid,
    # regardless of other users' licenses, as they need to manage the system.

    # Deactivate any existing license for this admin user first
    active_license = licenses_crud.get_active_license_for_user(conn, user_id)
    if active_license:
        if active_license['license_type'] == 'complet' and \
           (active_license['expiration_date'] is None or datetime.fromisoformat(active_license['expiration_date']) > datetime.now(timezone.utc)):
            logger.info(f"Admin user '{user_id}' already has an active 'complet' license. No new default license needed.")
            return True, "L'administrateur a déjà une licence 'complet' active.", active_license
        else:
            licenses_crud.deactivate_license(conn, active_license['license_id'])
            logger.info(f"Deactivated existing license '{active_license['license_id']}' for admin '{user_id}' before creating default admin license.")
            if activity_logs_crud:
                activity_logs_crud.add_activity_log(conn=conn, data={
                    "user_id": user_id, "action_type": "LICENSE_DEACTIVATED_FOR_ADMIN_DEFAULT",
                    "details": f"Existing license {active_license['license_id']} (type: {active_license['license_type']}) deactivated for admin default license creation.",
                    "related_entity_type": "License", "related_entity_id": active_license['license_id']
                })


    now = datetime.now(timezone.utc)
    expiration = now + timedelta(days=ADMIN_LICENSE_DURATION_DAYS)
    admin_license_key = f"ADMIN-DEFAULT-{str(uuid.uuid4()).upper()}" # Unique key for this instance
    current_machine_id = get_machine_identifier()

    admin_license_data = create_license_record(
        user_id=user_id,
        license_type="complet", # Admin always gets a 'complet' license
        license_key=admin_license_key,
        activation_date=now,
        expiration_date=expiration,
        machine_info=current_machine_id, # Tie it to the machine it was created on
        is_active=True
    )

    new_license_id = licenses_crud.add_license(conn, admin_license_data)
    if new_license_id:
        admin_license_data['license_id'] = new_license_id # Add the generated ID to the returned dict
        logger.info(f"Default admin license ('complet', {ADMIN_LICENSE_DURATION_DAYS} days) created successfully for user '{user_id}'. Expires: {expiration.isoformat()}")
        if activity_logs_crud:
            activity_logs_crud.add_activity_log(conn=conn, data={
                "user_id": user_id, "action_type": "LICENSE_ADMIN_DEFAULT_CREATED",
                "details": f"Default admin license created. Type: complet, Expires: {expiration.isoformat()}.",
                "related_entity_type": "License", "related_entity_id": new_license_id
            })
        return True, f"Licence administrateur par défaut activée. Valide jusqu'au {expiration.strftime('%d/%m/%Y %H:%M')}.", admin_license_data
    else:
        logger.error(f"Failed to add default admin license to DB for user '{user_id}'.")
        return False, "Erreur lors de l'enregistrement de la licence administrateur par défaut.", None


def check_license_validity(conn, user_id: str) -> tuple[bool, str | None, dict | None]:
    """
    Checks if the user has a valid, active, non-expired license.
    Returns: (is_valid, message, license_details_dict)
    """
    logger.debug(f"Checking license validity for user_id: {user_id}")
    license_details = licenses_crud.get_active_license_for_user(conn, user_id)

    if not license_details:
        logger.info(f"No active license record found for user {user_id}.")
        return False, "Aucune licence active trouvée pour cet utilisateur.", None

    # The get_active_license_for_user already checks is_active=1 and expiration_date > now
    # So, if a record is returned, it should be valid by definition of that CRUD.
    # However, we can add an explicit check here for robustness or if the CRUD logic changes.

    if not license_details.get('is_active'): # Should not happen if get_active_license_for_user works as expected
        logger.warning(f"License {license_details['license_id']} for user {user_id} is marked inactive.")
        return False, "La licence trouvée est marquée comme inactive.", license_details

    exp_date_str = license_details.get('expiration_date')
    if exp_date_str:
        try:
            expiration_date = datetime.fromisoformat(exp_date_str)
            if expiration_date.tzinfo is None: # Ensure it's offset-aware for comparison with timezone.utc
                 expiration_date = expiration_date.replace(tzinfo=timezone.utc)

            if expiration_date <= datetime.now(timezone.utc):
                logger.info(f"License {license_details['license_id']} for user {user_id} has expired on {exp_date_str}.")
                 # Optionally, deactivate it here if found expired
                licenses_crud.deactivate_license(conn, license_details['license_id'])
                return False, f"Votre licence de type '{license_details['license_type'].capitalize()}' a expiré le {expiration_date.strftime('%d/%m/%Y')}.", license_details
        except ValueError:
            logger.error(f"Invalid expiration_date format '{exp_date_str}' for license {license_details['license_id']}.")
            return False, "Format de date d'expiration invalide pour la licence.", license_details
    # If expiration_date is NULL, it's considered non-expiring (e.g. perpetual, though not typical for this system)

    logger.info(f"License {license_details['license_id']} for user {user_id} is valid. Type: {license_details['license_type']}.")
    return True, None, license_details # Valid, no error message, details of the license

def get_current_license_display_info(conn, user_id: str) -> str:
    """
    Returns a human-readable string about the user's current license status.
    """
    is_valid, message, lic = check_license_validity(conn, user_id)
    if is_valid and lic:
        exp_date_str = "Jamais"
        if lic.get('expiration_date'):
            try:
                exp_dt = datetime.fromisoformat(lic['expiration_date'])
                exp_date_str = exp_dt.strftime('%d/%m/%Y à %H:%M:%S')
            except ValueError:
                exp_date_str = "Date invalide"

        act_date_str = "Date inconnue"
        if lic.get('activation_date'):
            try:
                act_dt = datetime.fromisoformat(lic['activation_date'])
                act_date_str = act_dt.strftime('%d/%m/%Y')
            except ValueError:
                pass # Keep "Date inconnue"

        days_left_str = ""
        if lic.get('expiration_date'):
            try:
                exp_dt = datetime.fromisoformat(lic['expiration_date'])
                if exp_dt.tzinfo is None: exp_dt = exp_dt.replace(tzinfo=timezone.utc)
                remaining = exp_dt - datetime.now(timezone.utc)
                if remaining.days >= 0:
                    days_left_str = f" ({remaining.days} jours restants)"
                else:
                    days_left_str = " (Expirée)"
            except ValueError: pass

        return (
            f"Type de Licence : {lic.get('license_type', 'N/A').capitalize()}\n"
            f"Clé : {lic.get('license_key', 'N/A')[:15]}...\n"
            f"Activée le : {act_date_str}\n"
            f"Expire le : {exp_date_str}{days_left_str}\n"
            f"ID Machine : {lic.get('machine_info', 'N/A')[:10]}..."
        )
    elif message: # Invalid license, but we have a message
        return message
    else: # No license or error getting info
        return "Aucune information de licence disponible ou licence invalide."

